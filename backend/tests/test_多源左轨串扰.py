    assert {a["源键"] for a in 档} == {"渠甲", "渠丙"}
    assert all(a["金额分"] == 100 and a["笔数"] == 1 for a in 档)
    k9目, _ = 目录行("K9")
    assert k9目["差行数"] == 1 and k9目["valid"] is True
    k8目, _ = 目录行("K8")
    assert k8目["差行数"] == 1 and k8目["valid"] is True


