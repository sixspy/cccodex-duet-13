def test_不加锁会双成功_占锁即拒():
    多源.对齐锁.acquire()
    try:
        with pytest.raises(多源.对齐忙):
            对齐.跑对齐()
        with pytest.raises(多源.对齐忙):
            多源.设形态同票("合并")
        with pytest.raises(多源.对齐忙):
            多源.登记源同票({"源键": "渠己", "轨别": "左", "名称": "x"})
    finally:
        多源.对齐锁.release()


def test_并发对齐不双成功不混源():
    灌双源()
    结果, 错 = [], []

    def 跑():
        try:
            结果.append(对齐.跑对齐())
        except 多源.对齐忙:
            pass
        except Exception as e:  # noqa: BLE001
            错.append(e)

    闸 = threading.Barrier(4)
    def 起跑():
        闸.wait()
        跑()
    线程 = [threading.Thread(target=起跑) for _ in range(3)]
    for t in 线程:
        t.start()
    闸.wait()
    for t in 线程:
        t.join()
    assert not 错
    assert len(结果) >= 1  # 至少一票成功；并发双成功被锁拒
    k9 = 差行("K9")
    assert len(k9) == 2  # 双源并发灌入后仍是复合两行，不混源单行
    assert {x["源键"] for x in k9} == {"渠甲", "渠丙"}
    assert 多源.归档列表() == []  # 且无归档
    k9目, _ = 目录行("K9")
    assert k9目["valid"] is True


def test_结论源键同票匹配():
    左装载.装一批({"事件": [
        {"事件编号": "m1", "业务键": "K9", "金额分": 100, "源键": "渠甲", "事件时": "2026-11-24T00:00:00Z"},
        {"事件编号": "m2", "业务键": "K9", "金额分": 100, "源键": "渠丙", "事件时": "2026-11-24T00:00:01Z"},
        {"事件编号": "m4", "业务键": "K7", "金额分": 70, "源键": "渠丙", "事件时": "2026-11-24T00:00:02Z"},
    ]})
    右装载.装一批({"事件": [
        {"事件编号": "n1", "业务键": "K9", "金额分": 100, "源键": "核乙", "事件时": "2026-11-24T00:00:03Z"},
        {"事件编号": "n3", "业务键": "K6", "金额分": 30, "源键": "核乙", "事件时": "2026-11-24T00:00:04Z"},
    ]})
    对齐.跑对齐()
    悬 = {(r["业务键"], r["源键"], r["悬边"]) for r in 目录.悬列表()}
    assert ("K7", "渠丙", "左") in 悬  # 复合左悬带源键
    assert ("K6", "", "右") in 悬
    g = 结论.跑一次()
    assert g["是否通过"] is True  # 悬账与对齐差按 业务键+源键 同票自洽


